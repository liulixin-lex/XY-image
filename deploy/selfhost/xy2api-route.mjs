// Private route to the xy2api main site (FINDINGS G7, user request 52).
//
// The main site sits behind Cloudflare, which cuts a call after 125 s
// without an answer; 4K high-quality pictures take longer and were lost
// although the main site went on and billed them. Its origin address must
// stay unpublished, so the image server reaches it over a WireGuard tunnel
// instead (set up by hand on both servers, docs/XY_IMAGE_SELFHOST.md).
//
// `enable` adds the xy2api-route service: HAProxy answering for the main
// site's hostname (a network alias) inside this deployment's network. It
// passes TLS through untouched to the main site's own web server over the
// tunnel, so the API and worker keep calling https://<main site> with its
// real certificate and nothing in their configuration changes. When the
// tunnel cannot be reached, connections go to the public address through
// Cloudflare instead. Only connections switch over, never a request already
// sent, so nothing is sent twice. If this container stops, the alias goes
// away and the public address is used directly.
//
//   node deploy/selfhost/xy2api-route.mjs enable --dir <deployment> --private 10.77.0.1:443 [--stats-port 18404]
//   node deploy/selfhost/xy2api-route.mjs disable --dir <deployment>
// then `compose.sh --profile app up -d xy2api-route` (or `rm -sf xy2api-route`).
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import { pathToFileURL } from "node:url";

export const ROUTE_SERVICE = "xy2api-route";
export const ROUTE_IMAGE = "haproxy:3.2.25-alpine";
export const ROUTE_CONFIG = "xy2api-route.cfg";

/** `10.77.0.1:443` → { host, port }. IPv4 or a hostname. */
export function parsePrivateAddress(value) {
  const match = /^([a-zA-Z0-9.-]{1,253}):(\d{1,5})$/.exec(String(value ?? ""));
  const port = Number(match?.[2]);
  if (!match || !(port >= 1 && port <= 65535))
    throw new Error("Invalid --private: expected host:port");
  return { host: match[1], port };
}

/** The main site's hostname; the alias stands in for it on port 443. */
export function publicHostOf(xy2apiUrl) {
  const url = new URL(xy2apiUrl);
  if (url.protocol !== "https:" || url.port || url.pathname !== "/")
    throw new Error("The main site must be an https origin on port 443");
  return url.hostname;
}

export function renderRouteConfig({ privateAddress, publicHost }) {
  const { host, port } = parsePrivateAddress(privateAddress);
  if (!/^[a-zA-Z0-9.-]{1,253}$/.test(publicHost))
    throw new Error("Invalid main site hostname");
  return `# Generated by deploy/selfhost/xy2api-route.mjs. Edit there, not here.
# TLS passthrough to the main site ${publicHost}: over the private link
# (${host}:${port}) while it answers, else through Cloudflare.
global
  log stdout format raw local0 info
  maxconn 1024

defaults
  mode tcp
  log global
  option tcplog
  timeout connect 3s
  # Above the image calls' own 600 s limit: a 4K picture may take minutes
  # before the first byte comes back.
  timeout client 15m
  timeout server 15m
  timeout check 3s
  # A connection the private link refused or never answered is tried once
  # more, on the backup. Nothing was sent on it yet.
  retries 1
  option redispatch 1

resolvers public
  # Public DNS on purpose: inside this network the main site's name points
  # back at this container.
  nameserver cloudflare 1.1.1.1:53
  nameserver google 8.8.8.8:53
  resolve_retries 3
  timeout resolve 1s
  timeout retry 1s
  hold valid 30s

frontend xy2api_in
  bind :443
  default_backend main_site

backend main_site
  # One failed connection marks the link down at once (no wait for the
  # next check); two good checks 5 s apart bring it back.
  server private ${host}:${port} check inter 5s fastinter 1s downinter 5s fall 2 rise 2 observe layer4 error-limit 1 on-error mark-down
  server public ${publicHost}:443 backup check inter 30s resolvers public resolve-prefer ipv4 init-addr none

frontend stats
  mode http
  bind :8404
  stats enable
  stats uri /stats
`;
}

export function withRoute(compose, { publicHost, statsPort }) {
  if (!Number.isInteger(statsPort) || statsPort < 1024 || statsPort > 65535)
    throw new Error("Invalid --stats-port");
  const next = structuredClone(compose);
  next.services[ROUTE_SERVICE] = {
    image: ROUTE_IMAGE,
    profiles: ["app"],
    restart: "unless-stopped",
    read_only: true,
    cap_drop: ["ALL"],
    security_opt: ["no-new-privileges:true"],
    // HAProxy runs as an unprivileged user and listens on 443.
    sysctls: { "net.ipv4.ip_unprivileged_port_start": "0" },
    volumes: [`./${ROUTE_CONFIG}:/usr/local/etc/haproxy/haproxy.cfg:ro`],
    networks: { default: { aliases: [publicHost] } },
    // For the monitor (xy2apiRouteStatsUrl); loopback only.
    ports: [`127.0.0.1:${statsPort}:8404`],
    mem_limit: "128m",
    logging: {
      driver: "json-file",
      options: { "max-size": "10m", "max-file": "3" },
    },
    healthcheck: {
      test: ["CMD", "wget", "-q", "-O", "/dev/null", "http://127.0.0.1:8404/stats"],
      interval: "30s",
      timeout: "5s",
      retries: 3,
      start_period: "10s",
    },
  };
  return next;
}

export function withoutRoute(compose) {
  const next = structuredClone(compose);
  delete next.services[ROUTE_SERVICE];
  return next;
}

/** HAProxy stats CSV → Map of main_site server name → status ("UP", "DOWN", "UP 1/2"…). */
export function routeServers(csv) {
  const lines = String(csv).split("\n").filter(Boolean);
  const header = (lines.shift() ?? "").replace(/^#\s*/, "").split(",");
  const [proxy, server, status] = ["pxname", "svname", "status"].map((name) => header.indexOf(name));
  if (proxy < 0 || server < 0 || status < 0) return null;
  const servers = new Map();
  for (const line of lines) {
    const cells = line.split(",");
    if (cells[proxy] === "main_site" && !["FRONTEND", "BACKEND"].includes(cells[server]))
      servers.set(cells[server], cells[status]);
  }
  return servers;
}

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

export async function enableRoute({ dir, privateAddress, statsPort = 18404 }) {
  const deployment = await readJson(path.join(dir, "deployment.json"));
  const publicHost = publicHostOf(deployment.xy2api ?? "https://gguuai.com");
  const config = renderRouteConfig({ privateAddress, publicHost });
  const compose = withRoute(await readJson(path.join(dir, "compose.json")), {
    publicHost,
    statsPort,
  });
  // Readable by HAProxy's own user inside the container; no secrets in it.
  await writeFile(path.join(dir, ROUTE_CONFIG), config, { mode: 0o644 });
  await writeFile(path.join(dir, "compose.json"), `${JSON.stringify(compose, null, 2)}\n`, { mode: 0o600 });
  deployment.xy2apiRoute = { private: privateAddress, statsPort, publicHost };
  await writeFile(path.join(dir, "deployment.json"), `${JSON.stringify(deployment, null, 2)}\n`, { mode: 0o600 });
  return { service: ROUTE_SERVICE, publicHost, private: privateAddress, statsUrl: `http://127.0.0.1:${statsPort}/stats;csv` };
}

export async function disableRoute({ dir }) {
  const deployment = await readJson(path.join(dir, "deployment.json"));
  const compose = withoutRoute(await readJson(path.join(dir, "compose.json")));
  await writeFile(path.join(dir, "compose.json"), `${JSON.stringify(compose, null, 2)}\n`, { mode: 0o600 });
  delete deployment.xy2apiRoute;
  await writeFile(path.join(dir, "deployment.json"), `${JSON.stringify(deployment, null, 2)}\n`, { mode: 0o600 });
  return { service: ROUTE_SERVICE, removed: true };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    const { positionals, values } = parseArgs({
      allowPositionals: true,
      options: {
        dir: { type: "string" },
        private: { type: "string" },
        "stats-port": { type: "string" },
      },
    });
    const [command] = positionals;
    if (!values.dir || !path.isAbsolute(values.dir)) throw new Error("Missing absolute --dir");
    let result;
    if (command === "enable") {
      if (!values.private) throw new Error("Missing --private");
      result = await enableRoute({
        dir: values.dir,
        privateAddress: values.private,
        statsPort: values["stats-port"] ? Number(values["stats-port"]) : undefined,
      });
    } else if (command === "disable") result = await disableRoute({ dir: values.dir });
    else throw new Error("Usage: xy2api-route.mjs enable|disable --dir <deployment> [--private host:port] [--stats-port n]");
    console.log(JSON.stringify(result));
  } catch (error) {
    console.error(`[xy2api-route] ${error.message}`);
    process.exitCode = 1;
  }
}
